async function request(kind, path, method = 'GET', data, status = 200) {
  const response = await fetch(base + path, { method, headers: { ...(cookies[kind] ? { Cookie: cookies[kind] } : {}), ...(method !== 'GET' ? { Origin: base } : {}), ...(data && !(data instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, body: data ? data instanceof FormData ? data : JSON.stringify(data) : undefined, redirect: 'manual', signal: AbortSignal.timeout(90000) });
  const bytes = Buffer.from(await response.arrayBuffer());
  const body = response.headers.get('content-type')?.includes('application/json') ? JSON.parse(bytes) : bytes;
  assert.equal(response.status, status, method + ' ' + path + ': ' + bytes.toString().slice(0, 300));
  checks.push({ method, path: path.split('?')[0], status });
  return { response, bytes, body, data: body.data };
}
