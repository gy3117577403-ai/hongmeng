import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import ExcelJS from 'exceljs';
assert.equal(process.env.PURCHASING_QA_ALLOW, 'disposable-purchasing-runtime');
const origin = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:33284';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(origin).hostname));
const fixture = JSON.parse(readFileSync(process.env.PURCHASING_SELECTION_FIXTURE || '.local/purchasing-selection-fixture.json', 'utf8'));
const dir = resolve(process.env.PURCHASING_SELECTION_OUTPUT || 'output/playwright/purchasing-selection').replaceAll('\\', '/');
mkdirSync(dir, { recursive: true });
const generated = join(dir, 'browser-code.generated.cjs');
function cli(args) {
  const command = process.platform === 'win32' ? process.execPath : 'npx';
  const prefix = process.platform === 'win32' ? [join(dirname(process.execPath), 'node_modules/npm/bin/npx-cli.js')] : [];
  const r = spawnSync(command, [...prefix, '--yes', '--package', '@playwright/cli@0.1.19', 'playwright-cli', '-s=purchasing-selection', ...args], { encoding: 'utf8', timeout: 480000 });
  const output = ((r.stdout || '') + (r.stderr || '')).replace(/### Ran Playwright code\r?\n```[\s\S]*?```(?:\r?\n)?/g, '').replaceAll(fixture.password, '[disposable-password]');
  if (r.error || r.status) throw Error(r.error?.message || output);
  return output;
}
async function scenario(page, origin, f, dir) {
  const checks = [], errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  const check = (yes, label) => { if (!yes) throw Error(label); checks.push(label); };
  const shot = name => page.screenshot({ path: `${dir}/${name}.png`, fullPage: false, animations: 'disabled' });
  const stable = async () => { await page.waitForFunction(() => document.querySelector('.pc-table-wrap')?.getAttribute('aria-busy') === 'false'); };
  const login = async (username, path) => {
    await page.context().clearCookies(); await page.goto(origin + '/login?next=' + encodeURIComponent(path));
    await page.getByLabel('员工编号 / 管理账号').fill(username); await page.getByLabel('密码', { exact: true }).fill(f.password);
    await page.getByRole('button', { name: '登录', exact: true }).click(); await page.waitForURL(u => u.pathname === path.split('?')[0], { timeout: 60000 });
  };
  try {
    await page.setViewportSize({ width: 1366, height: 1024 });
    await login(f.user.username, '/workspace/purchases');
    await page.getByPlaceholder('搜索物品、编号、申请人或供应商').fill(f.marker);
    await page.waitForFunction(marker => document.querySelector('.pc-pagination')?.textContent.includes('共 26 条') && [...document.querySelectorAll('tbody tr')].every(r => r.textContent.includes(marker)), f.marker);
    await stable();
    await page.getByLabel('选择当前页全部记录', { exact: true }).check();
    check((await page.locator('.pc-selection').innerText()).includes('已选 12 项'), 'first page selects 12');
    await page.getByRole('button', { name: '下一页', exact: true }).click(); await stable();
    await page.getByLabel('选择当前页全部记录', { exact: true }).check();
    check((await page.locator('.pc-selection').innerText()).includes('已选 24 项'), 'second page appends to 24');
    check((await page.locator('.pc-selection').innerText()).includes('120.00'), 'cross-page amount includes all 24');
    await page.getByRole('button', { name: '上一页', exact: true }).click(); await stable();
    check(await page.locator('tbody input:checked').count() === 12, 'returning to first page preserves all checkboxes');
    await page.getByLabel('选择当前页全部记录', { exact: true }).uncheck();
    check((await page.locator('.pc-selection').innerText()).includes('已选 12 项'), 'deselecting page preserves off-page selection');
    await page.getByRole('button', { name: /选择全部筛选结果/ }).click();
    await page.waitForFunction(() => document.querySelector('.pc-selection')?.textContent.includes('已选 26 项'));
    await page.getByRole('button', { name: '查看已选', exact: true }).click();
    check((await page.getByLabel('跨页已选明细').innerText()).includes('尚未登记采购'), 'ineligible purchase explains why');
    check((await page.getByLabel('跨页已选明细').innerText()).includes('无可申请余额'), 'reserved reimbursement explains why');
    await page.getByRole('button', { name: '仅保留可请款 / 报销', exact: true }).click();
    check((await page.locator('.pc-selection').innerText()).includes('已选 24 项'), 'eligible-only keeps all 24 across pages');
    await page.getByRole('button', { name: '收起已选', exact: true }).click(); await shot('01-cross-page-selection');
    const downloadPromise = page.waitForEvent('download'); await page.getByRole('button', { name: '导出选中', exact: true }).click();
    const download = await downloadPromise; await download.saveAs(`${dir}/selected.xlsx`);
    await page.locator('.pc-selection').getByRole('button', { name: '请款 / 报销', exact: true }).click();
    const dialog = page.getByRole('dialog'); await dialog.waitFor();
    check((await dialog.innerText()).includes('分为 2 组'), 'different payees receive two explicit groups');
    check(await dialog.locator('li').count() === 24, 'review includes all 24 item lines');
    await shot('02-grouped-reimbursement');
    await dialog.getByRole('button', { name: '确认保存', exact: true }).click(); await dialog.waitFor({ state: 'hidden' }); await stable();
    const result = await page.request.get(origin + '/api/purchases?q=' + encodeURIComponent(f.marker) + '&pageSize=100');
    const data = (await result.json()).data;
    check(data.rows.filter(r => r.status === 'ORDERED').every(r => r.availableCents === 0), 'all eligible lines reserved exactly once after grouped submission');
    await page.getByLabel('入库状态', { exact: true }).selectOption('RECEIVED'); await stable();
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 2);
    check(await page.locator('.pc-receipt-badge.received').count() === 2, 'received filter matches both received records');
    check((await page.locator('tbody').innerText()).includes('已退货 2 件'), 'returns remain visible without erasing receipt history');
    await shot('03-receipt-status');
    await page.getByLabel('入库状态', { exact: true }).selectOption('PARTIAL'); await stable();
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 1);
    check((await page.locator('tbody').innerText()).includes('待收 2 件'), 'partial receipt shows remaining quantity');
    await login(f.accounts[0].username, '/workspace/warehouse?branch=samples&taskId=' + f.taskId);
    await page.getByRole('button', { name: '确认已配齐', exact: true }).waitFor();
    check((await page.locator('.sw-task-list').innerText()).includes(f.marker), 'warehouse-only user reads sample task and detail');
    await page.waitForFunction(() => Number(document.querySelector('.sb-week-switch button.active b')?.textContent) > 0);
    check(!(await page.getByLabel('样品类型与计划周').innerText()).includes('周数量暂不可用'), 'sample week data is available');
    await shot('04-warehouse-sample-access');
    const forbidden = await page.request.patch(origin + '/api/sample-tasks/' + f.taskId, { data: { action: 'SCHEDULE', expectedVersion: 1 }, headers: { origin } });
    check(forbidden.status() === 403, 'warehouse-only grant cannot edit sample planning');
    await page.getByRole('button', { name: '确认已配齐', exact: true }).click();
    await page.getByRole('button', { name: '更正状态', exact: true }).waitFor();
    check((await page.locator('.sw-state-actions').innerText()).includes('已配齐'), 'warehouse collaboration completes sample kitting');
    await shot('05-sample-completed');
    await login(f.accounts[1].username, '/workspace/warehouse?branch=samples&taskId=' + f.taskId);
    await page.locator('.sw-material-panel').waitFor();
    check(await page.getByRole('button', { name: '更正状态', exact: true }).count() === 0, 'read-only warehouse has no mutation button');
    const record = await page.request.get(origin + '/api/warehouse/sample-tasks/' + f.taskId + '/materials');
    const body = await record.json();
    const blocked = await page.request.patch(origin + '/api/warehouse/sample-tasks/' + f.taskId + '/materials', { data: { action: 'reopen', version: body.task.version, note: 'must be denied' }, headers: { origin } });
    check(blocked.status() === 403, 'read-only warehouse API mutation is denied');
    await page.route('**/api/warehouse/sample-tasks?**', route => route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ ok: false, error: '当前账号没有执行此操作的权限' }) }));
    await page.getByRole('button', { name: '刷新样品配料', exact: true }).click();
    await page.getByText('当前账号无权读取样品配料数据', { exact: true }).waitFor();
    check(await page.getByText('当前筛选没有配料任务', { exact: true }).count() === 0, 'permission failure never pretends there are zero tasks');
    await shot('06-permission-error-state');
    check(errors.length === 0, 'no browser runtime errors: ' + JSON.stringify(errors));
    return { passed: true, checks };
  } catch (error) { await shot('failure').catch(() => {}); throw error; }
}
try {
  writeFileSync(generated, `async page => { const scenario=${scenario.toString()}; return scenario(page,${JSON.stringify(origin)},${JSON.stringify(fixture)},${JSON.stringify(dir)}); }`);
  cli(['open', origin + '/login']);
  const output = cli(['run-code', '--filename', generated]); writeFileSync(join(dir, 'browser-runtime.txt'), output);
  assert.match(output, /"passed":\s*true/);
  const workbook = new ExcelJS.Workbook(); await workbook.xlsx.readFile(join(dir, 'selected.xlsx'));
  const sheet = workbook.worksheets[0]; assert.equal(sheet.rowCount, 25);
  assert.equal(new Set(sheet.getColumn(1).values.slice(2)).size, 24);
  assert.ok(sheet.getRow(1).values.includes('入库状态')); assert.ok(sheet.getRow(1).values.includes('待收数量'));
  writeFileSync(join(dir, 'browser-result.json'), JSON.stringify({ passed: true, exportRows: 24, checks: output }, null, 2));
  console.log(output); console.log('Export verified: 24 unique selected records, receipt status and remaining quantities.');
} finally { rmSync(generated, { force: true }); try { cli(['close']); } catch {} }
