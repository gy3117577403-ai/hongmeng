async function drawingAssociationScenario(page,origin,f,dir){
 const checks=[],errors=[];page.on('pageerror',error=>errors.push(String(error)));
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const shot=name=>page.screenshot({path:dir+'/'+name+'.png',fullPage:false,animations:'disabled'});
 const api=path=>page.evaluate(async path=>{const r=await fetch(path);return{status:r.status,body:await r.json()};},path);
 const dialog=()=>page.locator('.op-dialog');
 const picker=()=>page.getByRole('dialog',{name:'关联图纸资料库',exact:true});
 const save=async()=>{await dialog().getByRole('button',{name:'保存',exact:true}).click();await dialog().waitFor({state:'detached'});};
 try{
  await page.setViewportSize({width:1366,height:1024});await page.goto('about:blank');await page.context().clearCookies();
  await page.goto(origin+'/login?next='+encodeURIComponent('/weekly-plan-center?view=pool'));
  await page.getByLabel('员工编号 / 管理账号').fill(f.users.planner.username);await page.getByLabel('密码',{exact:true}).fill(f.password);
  await page.getByRole('button',{name:'登录',exact:true}).click();await page.waitForURL(u=>u.pathname==='/weekly-plan-center');
  await page.locator('.op-table tbody tr').first().waitFor();
  await page.locator('.op-tools').getByRole('button',{name:'新建订单',exact:true}).click();
  await dialog().getByLabel('客户',{exact:true}).fill(f.drawingCustomer);
  await dialog().getByLabel('产品规格 / 品番',{exact:true}).fill(f.drawingSpec);
  await dialog().getByLabel('订单数量',{exact:true}).fill('200');
  await dialog().getByLabel('准备备注',{exact:true}).fill('先配料，原图继续关联');
  await dialog().getByText('找到 2 个同规格档案，请选择',{exact:true}).waitFor();
  check(await dialog().getByRole('button',{name:'保存',exact:true}).isDisabled(),'ambiguous archives require a visible explicit choice before save');
  await shot('drawing-create-choice-1366x1024');
  const beforeScroll=await dialog().locator('.op-modal-body').evaluate(e=>e.scrollTop);
  await dialog().getByRole('button',{name:'选择已有资料',exact:true}).click();await picker().waitFor();
  await picker().getByRole('button',{name:'确认关联此档案',exact:true}).waitFor({state:'visible'});
  const candidate=picker().getByLabel('图纸档案候选').getByRole('button').filter({hasText:f.archives[1].libraryKey});
  await candidate.click();
  await picker().locator('img.preview-image').evaluateAll(async images=>{await Promise.all(images.map(img=>img.decode()));});
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[aria-label="关联图纸资料库"] img.preview-image')).some(img=>img.complete&&img.naturalWidth>0));
  check((await api('/api/planning/import/drawings?customer='+encodeURIComponent(f.drawingCustomer)+'&q='+encodeURIComponent(f.drawingSpec))).status===200,'planning-only collaborator can read archive choices');
  await shot('drawing-picker-preview-1366x1024');
  await page.setViewportSize({width:1920,height:1080});await shot('drawing-picker-preview-1920x1080');
  await page.setViewportSize({width:1366,height:1024});
  await page.keyboard.press('Escape');await picker().waitFor({state:'detached'});
  check(await dialog().isVisible()&&await dialog().getByLabel('订单数量',{exact:true}).inputValue()==='200','Escape closes only the archive picker and retains order input');
  check(await dialog().locator('.op-modal-body').evaluate(e=>e.scrollTop)===beforeScroll,'archive cancel preserves the parent scroll position');
  check(await dialog().getByRole('button',{name:'选择已有资料',exact:true}).evaluate(e=>e===document.activeElement),'archive cancel returns keyboard focus to its trigger');
  await dialog().getByRole('button',{name:'选择已有资料',exact:true}).click();await candidate.click();
  await picker().getByRole('button',{name:'确认关联此档案',exact:true}).click();await picker().waitFor({state:'detached'});
  check(await dialog().getByLabel(/^准备备注/).inputValue()==='先配料，原图继续关联','choosing an archive preserves the rest of the draft');
  await dialog().getByRole('button',{name:'预览',exact:true}).click();
  await page.getByRole('dialog',{name:'预览图纸资料',exact:true}).getByRole('button',{name:'返回订单',exact:true}).click();
  // Changing a meaningful version suffix invalidates the old association immediately.
  await dialog().getByLabel('产品规格 / 品番',{exact:true}).fill(f.drawingSpec+'-NEW');
  check(await dialog().getByRole('button',{name:'保存',exact:true}).isDisabled(),'changing specification invalidates the previous selection');
  await dialog().getByText('本次新建资料档案',{exact:true}).waitFor();
  await dialog().getByLabel('产品规格 / 品番',{exact:true}).fill('POOL-TRASH-ONLY');
  await dialog().getByText('档案在回收站，请先恢复；不会重复建档',{exact:true}).waitFor();
  check(await dialog().getByRole('button',{name:'保存',exact:true}).isDisabled(),'trash-only archive cannot silently create a duplicate');
  // A failed lookup is not permission to create an empty archive.
  await page.context().setOffline(true);
  await dialog().getByLabel('产品规格 / 品番',{exact:true}).fill(f.drawingSpec);
  await dialog().locator('.op-drawing-message[role=alert]').waitFor();
  check(await dialog().getByRole('button',{name:'保存',exact:true}).isDisabled(),'lookup failure blocks saving and retains the draft');
  await page.context().setOffline(false);await dialog().getByRole('button',{name:'重试',exact:true}).click();
  await dialog().getByText('找到 2 个同规格档案，请选择',{exact:true}).waitFor();
  await dialog().getByRole('button',{name:'选择已有资料',exact:true}).click();await candidate.click();
  await picker().getByRole('button',{name:'确认关联此档案',exact:true}).click();
  await dialog().getByLabel('订单号',{exact:true}).fill(f.marker+'-selected-order');await shot('drawing-create-linked-1366x1024');await save();
  let queue=(await api('/api/order-pool')).body;
  const created=queue.orders.find(o=>o.sourceOrderNo===f.marker+'-selected-order');
  check(created?.drawingLibraryItemId===f.archives[1].id&&created.drawingCount===1,'new order retains the chosen archive and its original image');
  check(created.batches.length===0&&created.preparedQuantity===0&&!created.customerDueDate,'archive selection creates no weekly allocation, material credit or delivery promise');
  const material=await api('/api/warehouse/material-orders?scope=pool&status=all');
  check(material.body.orders.some(o=>o.planOrderId===created.id),'selected order remains available for warehouse preparation');
  const row=page.locator('.op-table tbody tr').filter({hasText:f.drawingSpec});
  await row.getByRole('button',{name:'待核对',exact:true}).click();await page.getByRole('dialog',{name:'订单物料明细'}).waitFor();
  await page.getByRole('button',{name:'关闭订单缺料',exact:true}).click();check(await row.isVisible(),'material preview returns to the selected pool order');
  await page.getByRole('button',{name:'查看全部',exact:true}).click();
  await page.getByRole('button',{name:'导入订单池',exact:true}).click();
  await dialog().locator('input[type=file]').setInputFiles(f.associationFile);
  await dialog().getByText('2 行待确认图纸关联',{exact:true}).waitFor();
  check(await dialog().getByRole('button',{name:'导入有效行',exact:true}).isDisabled(),'import cannot bypass unresolved archive choices');
  await dialog().getByRole('button',{name:'选择已有资料',exact:true}).first().click();await candidate.click();
  await picker().getByRole('button',{name:'确认关联此档案',exact:true}).click();
  await dialog().getByRole('button',{name:'将第 2 行档案应用到另外 1 行同客户同规格',exact:true}).click();
  await shot('drawing-import-linked-1366x1024');
  await dialog().getByRole('button',{name:'导入有效行',exact:true}).click();await dialog().waitFor({state:'detached'});
  queue=(await api('/api/order-pool')).body;
  const imported=queue.orders.filter(o=>o.sourceOrderNo.startsWith(f.marker+'-assoc-import-'));
  check(imported.length===2&&imported.every(o=>o.drawingLibraryItemId===f.archives[1].id),'explicit bulk apply links both same-product rows to the chosen archive');
  await page.getByRole('button',{name:'查看全部',exact:true}).click();await page.getByRole('button',{name:'导入订单池',exact:true}).click();
  await dialog().locator('input[type=file]').setInputFiles(f.associationFile);
  await dialog().getByText('沿用原订单资料',{exact:false}).first().waitFor();
  check(await dialog().getByRole('button',{name:'更换',exact:true}).count()===0,'repeat import locks the original archive despite multiple same-product archives');
  await dialog().getByRole('button',{name:'导入有效行',exact:true}).click();await dialog().waitFor({state:'detached'});
  check((await api('/api/order-pool')).body.orders.filter(o=>o.sourceOrderNo.startsWith(f.marker+'-assoc-import-')).length===2,'repeat import creates no duplicate orders');
  check(errors.length===0,'drawing association interaction has no JavaScript page errors');
  return{passed:true,checks};
 }catch(error){await page.context().setOffline(false);await shot('drawing-failure');throw Error(String(error)+'; browser errors: '+errors.join('; ')+'; labels: '+JSON.stringify(await dialog().locator('label').allTextContents())+'; aria: '+await dialog().getAttribute('aria-hidden'));}
}
