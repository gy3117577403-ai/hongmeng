import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
const origin = process.env.REPORT_RECOVERY_QA_BASE || 'http://127.0.0.1:33135';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname) || process.env.REPORT_RECOVERY_QA_ALLOW !== 'disposable-reporting-runtime') throw Error('Disposable reporting runtime required');
const fixture = JSON.parse(readFileSync(process.env.ROUTE_REPLACEMENT_QA_FIXTURE, 'utf8').replace(/^\uFEFF/, ''));
const dir = process.env.ROUTE_REPLACEMENT_QA_OUTPUT || 'output/playwright/route-replacement'; mkdirSync(dir, { recursive: true });
function cli(args) {
  const command = process.platform === 'win32' ? process.execPath : 'npx';
  const prefix = process.platform === 'win32' ? [join(dirname(process.execPath), 'node_modules/npm/bin/npx-cli.js')] : [];
  const result = spawnSync(command, [...prefix, '--yes', '--package', '@playwright/cli@0.1.19', 'playwright-cli', '-s=route-replacement-release', ...args], { encoding: 'utf8', timeout: 180000, windowsHide: true });
  const output = ((result.stdout || '') + (result.stderr || '')).replace(/### Ran Playwright code\r?\n```[\s\S]*?```(?:\r?\n)?/g, '').replaceAll(fixture.password, '[disposable-password]');
  if (result.error || result.status) throw Error(result.error?.message || output); return output;
}
try {
  cli(['open', origin + '/login']); writeFileSync(dir+'/initial.txt', cli(['snapshot']));
  const code = `async page => {
    const base=${JSON.stringify(origin)}, f=${JSON.stringify(fixture)}, out=${JSON.stringify(dir)}, checks=[], errors=[];
    const check=(condition,message)=>{if(!condition)throw Error(message);checks.push(message)};
    page.on('pageerror',e=>errors.push(String(e)));
    let cookie='';
    const login=async kind=>{const r=await page.request.post(base+'/api/auth/login',{headers:{Origin:base},data:{username:f.users[kind].username,password:f.password}});check(r.status()===200,'login '+kind);cookie=(r.headers()['set-cookie']||'').match(/hm_session=[^;]+/)?.[0]||''};
    const get=async path=>{const r=await page.request.get(base+path,{headers:{Cookie:cookie}});check(r.status()===200,'read '+path.split('?')[0]);return r.json()};
    await login('admin');
    const first=f.routeOrders[0];
    const report=await page.request.post(base+'/api/process-management/routes/'+first.routeId+'/completions',{headers:{Cookie:cookie,Origin:base},data:{stepId:first.firstStepId,expectedRouteVersion:0,processedQty:40,defectQty:0,employeeIds:[f.users.operator.employeeId],workDate:f.workDate,idempotencyKey:f.marker+'-first',expectedUserId:f.users.admin.id,allowPending:true}});
    check(report.status()===200,'existing first operation reported through real API');
    await page.setViewportSize({width:1366,height:1024});
    await page.goto(base+'/workspace/product-times?itemId='+f.itemId);
    const old=page.locator('article').filter({has:page.getByRole('button',{name:'移除导通',exact:true})});
    await old.getByRole('button',{name:'替换工序',exact:true}).click();
    await page.getByRole('button',{name:'线序检验 后端',exact:true}).first().click();
    const row=page.locator('article').filter({has:page.getByRole('button',{name:'移除线序检验',exact:true})});
    check(await row.getByLabel('单次标准时间（秒）',{exact:true}).inputValue()==='','replacement requires its own standard instead of borrowing the old value');
    await row.getByLabel('单次标准时间（秒）',{exact:true}).fill('2');
    await page.getByRole('button',{name:'保存并预览同步',exact:true}).click();
    await page.getByLabel('生效范围',{exact:true}).selectOption('work_orders');
    await page.getByRole('checkbox',{name:first.code,exact:true}).check();
    await page.getByRole('button',{name:'重新计算影响',exact:true}).click();
    const confirm=page.getByRole('button',{name:'确认发布并同步 1 张未完成工单',exact:true});
    await confirm.waitFor();check(await confirm.isEnabled(),'save and structured scope selection produce an actionable preview');
    check(await page.locator('[role=dialog] input[type=text][required],[role=dialog] textarea[required]').count()===0,'no mandatory free text');
    await page.screenshot({path:out+'/tablet-preview.png',fullPage:true});await confirm.click();
    await page.getByRole('button',{name:'完成',exact:true}).waitFor({timeout:90000});
    await page.screenshot({path:out+'/tablet-applied.png',fullPage:true});
    const selected=(await get('/api/field-report/tickets/'+first.publicCode)).data;
    const other=(await get('/api/field-report/tickets/'+f.routeOrders[1].publicCode)).data;
    check(selected.context.routeSteps.some(step=>step.processName==='线序检验'),'original QR reads replacement');
    check(!selected.context.routeSteps.some(step=>step.processName==='导通'),'retired process removed from active reporting choices');
    check(other.context.routeSteps.some(step=>step.processName==='导通'),'unselected order retains old process');
    await login('operator');await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/field-report/'+first.publicCode);
    await page.getByText(/^线序检验/).first().waitFor();
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'mobile QR has no horizontal overflow');
    await page.screenshot({path:out+'/phone-original-qr.png',fullPage:true});
    await page.locator('article').filter({hasText:'线序检验'}).getByRole('button',{name:'选择此工序报工',exact:true}).click();
    const sheet=page.getByRole('dialog');await sheet.getByRole('textbox',{name:'实际报工 套',exact:true}).fill('40');
    await sheet.getByRole('button',{name:'确认报工并自动记工',exact:true}).click();
    await page.getByRole('button',{name:'确认全部报工',exact:true}).click();
    await page.locator('.field-report-success').waitFor({timeout:90000});
    const replacement=selected.context.routeSteps.find(step=>step.processName==='线序检验');
    const after=(await get('/api/field-report/tickets/'+first.publicCode+'?stepId='+replacement.id)).data;
    check(after.context.reportedQty===40 && after.context.recentCompletions.length===1,'replacement reports successfully on the original mobile QR');
    await page.screenshot({path:out+'/phone-replacement-reported.png',fullPage:true});
    check(errors.length===0,'no uncaught browser errors: '+errors.join(';'));
    return {passed:true,checks};
  }`;
  const codeFile=dir+'/browser.generated.cjs';writeFileSync(codeFile,code);
  const result=cli(['run-code','--filename',codeFile]);writeFileSync(dir+'/runtime.txt',result);
  if (!/"passed":\s*true/.test(result)) throw Error(result); console.log(result);
} finally { cli(['close']); }
