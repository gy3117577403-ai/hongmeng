import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { prisma } from '../lib/prisma';
import { mutatePurchasing, type PcActor } from '../lib/purchasing-service';
import { purchasingDetail, loadPurchasing } from '../lib/purchasing-queries';
import type { PcInput } from '../lib/purchasing-domain';

test('received personal advances: audit, review, fund replacement, actual refunds and stock preservation', { skip: process.env.RUN_DB_INTEGRATION !== '1', timeout: 120000 }, async () => {
  const database = new URL(process.env.DATABASE_URL!);
  assert.ok(['localhost', '127.0.0.1'].includes(database.hostname) && /(_ci|_test)$/.test(database.pathname), 'disposable database required');
  const marker = 'amount-' + randomUUID(), date = new Date().toLocaleDateString('sv-SE', { timeZone: 'Asia/Shanghai' });
  const buyer = await prisma.user.create({ data: { username: marker, displayName: '隔离验收', passwordHash: 'test', laborRole: 'ADMIN' } });
  const finance = await prisma.user.create({ data: { username: marker + '-finance', displayName: '隔离验收', passwordHash: 'test' } });
  const stranger = await prisma.user.create({ data: { username: marker + '-other', displayName: '隔离验收', passwordHash: 'test' } });
  const run = async (input: PcInput, who: PcActor = buyer, key = randomUUID()) => await mutatePurchasing(input, who, key) as Record<string, any>;
  const settings = await prisma.pcSettings.findUnique({ where: { id: 'purchasing' } });
  await run({ action: 'SAVE_SETTINGS', ownerId: buyer.id, version: settings?.version, reason: marker,
    purchaseApproverIds: [buyer.id], buyerIds: [buyer.id], fundApproverIds: [finance.id], financeIds: [finance.id] });
  const line = (id: string) => prisma.pcLine.findUniqueOrThrow({ where: { id } });
  const entry = async (id: string) => ({ id, version: (await line(id)).version });
  const request = await run({ action: 'SAVE_REQUEST', submit: true, purpose: marker, lines: [{ name: marker, spec: 'M8', unit: '件', quantity: 10, estimateCents: 10000, needDate: date }] });
  const id = request.lineIds[0];
  await run({ action: 'APPROVE_LINES', entries: [await entry(id)] });
  await run({ action: 'PURCHASE', entries: [{ ...await entry(id), unitPrice: '10' }], settlement: 'ADVANCE', supplier: marker,
    payeeUserId: buyer.id, payee: marker, bank: '测试银行', account: 'TEST-ONLY', eta: date });
  await run({ action: 'RECEIVE', entries: [{ ...await entry(id), quantity: 10 }], date, warehouse: '测试仓', location: 'A' });
  const stockBefore = await prisma.pcStockBalance.findMany({ where: { lineId: id } });
  const movementsBefore = await prisma.pcStockMovement.count({ where: { lineId: id } });
  const correct = async (amount: number, who: PcActor = buyer) => run({ action: 'CORRECT_ADVANCE_AMOUNT', ...await entry(id), actualCents: amount, reason: '报销核对原价填写错误' }, who);
  await assert.rejects(correct(12000, stranger), /职责/);
  const first = await correct(12000); assert.equal(first.status, 'APPLIED');
  assert.equal((await line(id)).actualCents, 12000);
  const fund = await run({ action: 'CREATE_FUND', entries: [await entry(id)], amountCents: 12000 });
  const getFund = () => prisma.pcFund.findUniqueOrThrow({ where: { id: fund.id } });
  await run({ action: 'APPROVE_FUNDS', id: fund.id, version: (await getFund()).version }, finance);
  const correction = await correct(10000); assert.equal(correction.status, 'PENDING');
  const c = await prisma.pcAmountCorrection.findUniqueOrThrow({ where: { id: correction.correctionId } });
  const review = { action: 'APPROVE_AMOUNT_CORRECTION', correctionId: c.id, correctionVersion: c.version, reason: '已核对采购凭证' };
  await assert.rejects(run(review, buyer), /职责/);
  await assert.rejects(run({ action: 'PAY', id: fund.id, version: (await getFund()).version, amountCents: 10000, date, reference: 'blocked', source: '测试' }, finance), /复核/);
  await assert.rejects(correct(11000), /复核/);
  const reviewKey = randomUUID(); await run(review, finance, reviewKey); await run(review, finance, reviewKey);
  assert.equal((await getFund()).status, 'RETURNED');
  assert.equal((await line(id)).reservedCents, 0);
  const secondFund = await run({ action: 'CREATE_FUND', entries: [await entry(id)], amountCents: 10000 });
  const second = () => prisma.pcFund.findUniqueOrThrow({ where: { id: secondFund.id } });
  await run({ action: 'APPROVE_FUNDS', id: secondFund.id, version: (await second()).version }, finance);
  await run({ action: 'PAY', id: secondFund.id, version: (await second()).version, amountCents: 10000, date, source: '公司账户', reference: marker }, finance);
  const paymentBefore = await prisma.pcPayment.findMany({ where: { fundId: secondFund.id } });
  const invoiceFile = await prisma.pcAttachment.create({ data: { objectKey: 'test/' + randomUUID(), originalName: '测试票据.pdf', contentType: 'application/pdf', size: 10, actorId: buyer.id, actorName: buyer.displayName } });
  await run({ action: 'INVOICE', entries: [await entry(id)], amountCents: 10000, kind: 'NORMAL', number: randomUUID(), date, attachmentIds: [invoiceFile.id] });
  assert.ok((await line(id)).completedAt, 'fully received, invoiced and paid line is completed');
  const invoicesBefore = await prisma.pcInvoiceLine.findMany({ where: { lineId: id } });
  const lower = await correct(8000);
  const lowerC = await prisma.pcAmountCorrection.findUniqueOrThrow({ where: { id: lower.correctionId } });
  assert.equal(lowerC.reviewRole, 'FINANCE');
  await run({ action: 'APPROVE_AMOUNT_CORRECTION', correctionId: lowerC.id, correctionVersion: lowerC.version, reason: '核对多报金额' }, finance);
  const refund = await prisma.pcReturn.findFirstOrThrow({ where: { lineId: id, kind: 'AMOUNT_CORRECTION' } });
  assert.equal(refund.refundDueCents, 2000); assert.equal(refund.quantity, 0); assert.equal(refund.stockId, null);
  assert.equal((await line(id)).paidCents, 10000); assert.equal((await line(id)).refundedCents, 0);
  assert.equal((await line(id)).completedAt, null, 'a price correction reopens financial follow-up without undoing receipt');
  assert.equal((await line(id)).invoiceCents, 10000, 'original invoice awaits explicit credit correction');
  await assert.rejects(correct(9000), /待退回/);
  await run({ action: 'REFUND', id: refund.id, version: refund.version, amountCents: 2000, destination: 'COMPANY', date, reference: marker + '-refund' }, finance);
  const higher = await correct(11000);
  const higherC = await prisma.pcAmountCorrection.findUniqueOrThrow({ where: { id: higher.correctionId } });
  await run({ action: 'APPROVE_AMOUNT_CORRECTION', correctionId: higherC.id, correctionVersion: higherC.version, reason: '新增核对凭证' }, finance);
  const available = await run({ action: 'CREATE_FUND', entries: [await entry(id)], amountCents: 3000 });
  assert.ok(available.id, 'net paid 8000 against corrected 11000 permits exactly 3000');
  await assert.rejects(run({ action: 'CREATE_FUND', entries: [await entry(id)], amountCents: 1 }), /余额/);
  assert.deepEqual(await prisma.pcStockBalance.findMany({ where: { lineId: id } }), stockBefore);
  assert.equal(await prisma.pcStockMovement.count({ where: { lineId: id } }), movementsBefore);
  assert.deepEqual(await prisma.pcPayment.findMany({ where: { fundId: secondFund.id } }), paymentBefore);
  assert.deepEqual(await prisma.pcInvoiceLine.findMany({ where: { lineId: id } }), invoicesBefore);
  assert.equal((await line(id)).receivedQty, 10);
  const detail = await purchasingDetail(id, finance); assert.equal(detail.kind, 'line');
  if (detail.kind === 'line') assert.equal(detail.record.amountCorrections.length, 4);
  const third = () => prisma.pcFund.findUniqueOrThrow({ where: { id: available.id } });
  await run({ action: 'APPROVE_FUNDS', id: available.id, version: (await third()).version }, finance);
  await run({ action: 'PAY', id: available.id, version: (await third()).version, amountCents: 1000, date, source: '公司账户', reference: marker + '-partial' }, finance);
  const partial = await correct(10000);
  const partialC = await prisma.pcAmountCorrection.findUniqueOrThrow({ where: { id: partial.correctionId } });
  await run({ action: 'APPROVE_AMOUNT_CORRECTION', correctionId: partialC.id, correctionVersion: partialC.version, reason: '部分付款后核对' }, finance);
  assert.equal((await third()).status, 'CLOSED'); assert.equal((await third()).amountCents, 1000); assert.equal((await third()).paidCents, 1000);
  assert.equal((await line(id)).payableCents - (await line(id)).reservedCents + (await line(id)).refundedCents, 1000);
  const rejected = await correct(10500);
  const rejectedC = await prisma.pcAmountCorrection.findUniqueOrThrow({ where: { id: rejected.correctionId } });
  await run({ action: 'REJECT_AMOUNT_CORRECTION', correctionId: rejectedC.id, correctionVersion: rejectedC.version, reason: '依据不足退回核对' }, finance);
  assert.equal((await line(id)).actualCents, 10000, 'a rejected correction must not alter money facts');
  await assert.rejects(run({ action: 'APPROVE_AMOUNT_CORRECTION', correctionId: rejectedC.id, correctionVersion: rejectedC.version, reason: '过期复核' }, finance), /刷新|变化|版本|处理/);
  assert.ok(await loadPurchasing({ view: 'all', q: marker } as any, buyer));
  await prisma.$disconnect();
});
